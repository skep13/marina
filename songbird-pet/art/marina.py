#!/usr/bin/env python3
"""Marina as a 44x48 1-bit sprite for the S3 pet.

Hand-drawn pixel art from her VRM model: the ahoge curling over her head, light lavender hair
that flares wide and wavy over her shoulders (proportions taken from a
trace of the model render), long side-swept bangs, the black ribbon with\nits tails on her right, wide droopy eyes with slit pupils, the moon choker,
choker, and the black hoodie with its drawstrings and moon print.

Run to write ../firmware/main/MarinaSprite.h and marina_preview.png.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from pixels import W, H, blank, px, ellipse, poly, line, show  # noqa: E402


def marina(eyes="open"):
    g = blank()
    # ahoge: one strand rising from her crown and curling into an open loop
    line(g, 22, 6, 21, 3, 1)
    for x, y in ((20, 2), (21, 1), (22, 0), (23, 0), (24, 0), (25, 0), (26, 0), (27, 0),
                 (28, 0), (29, 0), (30, 1), (31, 1), (32, 2), (31, 3), (30, 3), (29, 4),
                 (28, 4), (27, 4), (26, 4)):
        px(g, x, y)

    # hair: rounded crown, long and wavy, flaring over her shoulders
    ellipse(g, 22, 17, 13, 11, fill=True)
    poly(g, [(9, 15), (35, 15), (37, 22), (38, 28), (40, 32), (42, 36), (41, 40),
             (39, 38), (37, 41), (35, 38), (33, 41), (31, 37), (29, 34),
             (15, 34), (13, 37), (11, 41), (9, 38), (7, 41), (5, 38), (3, 40),
             (2, 36), (4, 32), (6, 28), (7, 22)])
    # strands: dark partings, sweeping the way the bangs fall
    line(g, 24, 7, 18, 16, 0)
    line(g, 28, 8, 31, 15, 0)
    line(g, 9, 24, 7, 33, 0)
    line(g, 35, 24, 37, 33, 0)
    line(g, 12, 30, 10, 38, 0)
    line(g, 32, 30, 34, 38, 0)

    # face below long side-swept bangs that reach down to her eyes
    poly(g, [(13, 21), (31, 21), (31, 27), (28, 31), (25, 33), (19, 33), (16, 31), (13, 27)], 0)
    fringe = [(13, 22), (15, 19), (17, 22), (19, 19), (20, 21), (22, 19), (24, 23), (25, 20),
              (27, 22), (29, 19), (31, 21)]
    for (x0, y0), (x1, y1) in zip(fringe, fringe[1:]):
        poly(g, [(x0, 18), (x0, y0), (x1, y1), (x1, 18)], 1)

    # ribbon high on her right (viewer's left): crossed bow, two long tails
    poly(g, [(6, 8), (11, 10), (7, 13)], 0)
    poly(g, [(15, 6), (11, 10), (16, 11)], 0)
    for x, y in ((10, 10), (11, 10), (11, 9)):
        px(g, x, y, 1)                           # the knot
    line(g, 10, 11, 8, 20, 0)                    # tails hanging through the hair
    line(g, 12, 11, 12, 19, 0)

    # eyes: wide and a little droopy - dark lash flicking up at the outer
    # corner, lit iris, vertical slit pupil, two highlights
    for ex, outer in ((15, -1), (25, 1)):
        if eyes == "open":
            line(g, ex - 1, 24, ex + 5, 24, 1)                     # upper lash
            line(g, ex, 23, ex + 4, 23, 1)
            px(g, ex + (6 if outer > 0 else -2), 23, 1)            # outer flick
            poly(g, [(ex, 25), (ex + 4, 25), (ex + 4, 28), (ex + 3, 29), (ex + 1, 29), (ex, 28)], 1)
            poly(g, [(ex + 1, 25), (ex + 3, 25), (ex + 3, 28), (ex + 1, 28)], 0)   # pupil
            px(g, ex + 3, 25, 1)                                   # highlights
            px(g, ex + 1, 28, 1)
        elif eyes == "closed":
            line(g, ex - 1, 27, ex + 5, 27, 1)
            px(g, ex + (5 if outer > 0 else -1), 26)
            line(g, ex, 28, ex + 4, 28, 1)
        elif eyes == "happy":
            line(g, ex, 28, ex + 2, 25, 1)
            line(g, ex + 2, 25, ex + 4, 28, 1)
            line(g, ex, 29, ex + 2, 26, 1)
            line(g, ex + 2, 26, ex + 4, 29, 1)
    px(g, 22, 32, 1)                             # small mouth

    # neck, thin choker, crescent-moon pendant
    line(g, 19, 33, 19, 35, 1)
    line(g, 25, 33, 25, 35, 1)
    line(g, 18, 35, 26, 35, 1)
    for x, y in ((21, 36), (22, 37), (23, 36)):
        px(g, x, y, 1)
    # hoodie: hood opening, drawstrings, moon print, shoulders under the hair
    line(g, 15, 38, 19, 42, 1)
    line(g, 29, 38, 25, 42, 1)
    line(g, 19, 42, 19, 46, 1)
    line(g, 25, 42, 25, 46, 1)
    for x, y in ((22, 44), (21, 45), (21, 46), (22, 47), (23, 43)):
        px(g, x, y)
    line(g, 4, 43, 1, 47, 1)
    line(g, 40, 43, 43, 47, 1)
    return g


def header(path):
    out = ["#pragma once",
           "// MarinaSprite - Marina as the pet, 44x48 1-bit, three eye states.",
           "// Generated by songbird-pet/art/marina.py - edit that, not this.",
           "#include <stdint.h>", "",
           f"#define MARINA_W {W}", f"#define MARINA_H {H}", ""]
    for name in ("open", "closed", "happy"):
        g = marina(name)
        data = []
        for row in g:
            for b in range(0, W, 8):
                v = 0
                for i in range(8):
                    if b + i < W and row[b + i]:
                        v |= 0x80 >> i
                data.append(v)
        out.append(f"static const uint8_t MARINA_{name.upper()}[] = {{")
        for i in range(0, len(data), 12):
            out.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 12]) + ",")
        out += ["};", ""]
    with open(path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    header(os.path.join(HERE, "..", "firmware", "main", "MarinaSprite.h"))
    show([marina("open"), marina("closed"), marina("happy")], os.path.join(HERE, "marina_preview.png"))
    print("wrote MarinaSprite.h and marina_preview.png")
